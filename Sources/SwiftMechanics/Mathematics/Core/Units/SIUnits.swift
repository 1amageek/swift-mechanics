    public static let newtonMetre = UnitDefinition(validatedSymbol: "N*m", dimension: .energy, scale: 1, offset: 0)
    public static let pascal = UnitDefinition(validatedSymbol: "Pa", dimension: .pressure, scale: 1, offset: 0)
    public static let ampere = UnitDefinition(validatedSymbol: "A", dimension: .electricCurrent, scale: 1, offset: 0)
    public static let volt = UnitDefinition(validatedSymbol: "V", dimension: .voltage, scale: 1, offset: 0)
    public static let ohm = UnitDefinition(validatedSymbol: "ohm", dimension: .resistance, scale: 1, offset: 0)
    public static let kelvin = UnitDefinition(validatedSymbol: "K", dimension: .temperature, scale: 1, offset: 0)
    public static let celsius = UnitDefinition(validatedSymbol: "degC", dimension: .temperature, scale: 1, offset: 273.15)
}
